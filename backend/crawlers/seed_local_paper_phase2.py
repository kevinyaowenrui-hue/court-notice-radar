def ingest_phase2(db):
    added = 0
    now = datetime.now()
    for item in EXTRA_ITEMS:
        raw_id = f"53bk_p2_{item['city']}_{stable_hash(item['title'])}"
        existing = db.query(CourtNotice).filter(
            CourtNotice.platform == "local_paper",
            CourtNotice.raw_id == raw_id
        ).first()

        pub_date = now - timedelta(days=random.randint(1, 25), hours=random.randint(1, 14))
        module = categorize_notice_module(item['title'], item['content'], item.get('cat', ''), "local_paper")
        if item.get("price") and "拍卖" in item['title']:
            module = "拍卖公告"
            notice_type = "报刊司法拍卖"
        elif "债权" in item['title'] or "催收" in item['title'] or "资产包" in item['title']:
            module = "债权转让"
            notice_type = "报刊债权转让"
        else:
            module = "公告"
            notice_type = "报刊司法与法定公告"

        paper_obj = next((p for p in HENAN_LOCAL_PAPERS if p["paper"] == item["paper"]), None)
        source_url = paper_obj["url"] if paper_obj else "http://www.53bk.com/"

        if not existing:
            notice = CourtNotice(
                platform="local_paper",
                raw_id=raw_id,
                court_name=item["court"],
                case_number="",
                parties="",
                notice_type=notice_type,
                module_type=module,
                title=f"《{item['paper']}》刊登: {item['title']}",
                content_text=f"报纸媒体：{item['paper']}（河南 · {item['city']}）\n所属版面：{item['edition']}\n刊登标题：{item['title']}\n刊登日期：{pub_date.strftime('%Y-%m-%d')}\n{item['content']}",
                publish_time=pub_date,
                source_url=source_url,
                starting_price=item.get("price"),
                eval_price=item.get("eval"),
                auction_stage=item.get("stage"),
                asset_category=item.get("cat"),
                is_henan=True,
                henan_city=item["city"],
                henan_tag=f"河南属地报纸公告专版 (《{item['paper']}》· {item['city']})"
            )
            db.add(notice)
            added += 1

    db.commit()
